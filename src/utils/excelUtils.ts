function decodeBufferToUtf8(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  if (bytes.length >= 2 && bytes[0] === 0xff && bytes[1] === 0xfe) {
    return new TextDecoder('utf-16le').decode(bytes.subarray(2));
  }
  if (bytes.length >= 2 && bytes[0] === 0xfe && bytes[1] === 0xff) {
    const swapped = new Uint8Array(bytes.length - 2);
    for (let i = 2; i + 1 < bytes.length; i += 2) {
      swapped[i - 2] = bytes[i + 1];
      swapped[i - 1] = bytes[i];
    }
    return new TextDecoder('utf-16le').decode(swapped);
  }
  // UTF-8 BOM + strict/standard UTF-8 decode
  const text = new TextDecoder('utf-8').decode(bytes);
  return text.replace(/^\uFEFF/, '');
}

function detectCsvDelimiter(text: string): string {
  const sampleLines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l.length > 0)
    .slice(0, 8);

  const candidates = [',', ';', '\t'];
  let best = ',';
  let bestScore = -1;

  for (const delim of candidates) {
    let counts = 0;
    let inQuotes = false;
    for (const line of sampleLines) {
      for (let i = 0; i < line.length; i++) {
        const ch = line[i];
        if (ch === '"') inQuotes = !inQuotes;
        else if (!inQuotes && ch === delim) counts++;
      }
      inQuotes = false;
    }
    if (counts > bestScore) {
      bestScore = counts;
      best = delim;
    }
  }

  return best;
}

function parseHtmlTablesToWorkbook(html: string): XLSX.WorkBook | null {
  if (typeof DOMParser === 'undefined') return null;
  const parser = new DOMParser();
  const doc = parser.parseFromString(html, 'text/html');
  const tables = Array.from(doc.querySelectorAll('table'));
  if (tables.length === 0) return null;

  let targetTable = tables[0];
  let maxRows = targetTable.querySelectorAll('tr').length;
  for (const tbl of tables) {
    const count = tbl.querySelectorAll('tr').length;
    if (count > maxRows) {
      maxRows = count;
      targetTable = tbl;
    }
  }

  const matrix: string[][] = [];
  const trs = Array.from(targetTable.querySelectorAll('tr'));
  for (const tr of trs) {
    const cells = Array.from(tr.querySelectorAll('th, td')).map((td) =>
      (td.textContent || '').replace(/\s+/g, ' ').trim()
    );
    if (cells.some((c) => c !== '')) {
      matrix.push(cells);
    }
  }

  if (matrix.length === 0) return null;
  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.aoa_to_sheet(matrix);
  XLSX.utils.book_append_sheet(wb, ws, 'Data');
  return wb;
}

/**
 * Membaca file .xlsx, .xls, maupun .csv menggunakan SheetJS (XLSX) dari ArrayBuffer.
 * Khusus file CSV didekode sebagai UTF-8 dengan raw=true agar angka 0 di depan NIS/NISN tidak hilang.
 */
export async function readSpreadsheetWorkbook(file: File): Promise<XLSX.WorkBook> {
  const lowerName = file.name.toLowerCase();
  const buffer = await file.arrayBuffer();
  const bytes = new Uint8Array(buffer);

  if (bytes.length === 0) {
    throw new Error(`File "${file.name}" kosong (0 byte).`);
  }

  const isZipXlsx = bytes.length >= 4 && bytes[0] === 0x50 && bytes[1] === 0x4b;
  const isOleXls =
    bytes.length >= 4 &&
    bytes[0] === 0xd0 &&
    bytes[1] === 0xcf &&
    bytes[2] === 0x11 &&
    bytes[3] === 0xe0;

  if (lowerName.endsWith('.csv') || lowerName.endsWith('.tsv') || (!isZipXlsx && !isOleXls)) {
    const utf8Text = decodeBufferToUtf8(buffer);
    const trimmed = utf8Text.trim();
    const lowerHead = trimmed.slice(0, 600).toLowerCase();

    if (
      lowerHead.includes('<table') ||
      lowerHead.startsWith('<html') ||
      lowerHead.startsWith('<!doctype')
    ) {
      const htmlWb = parseHtmlTablesToWorkbook(utf8Text);
      if (htmlWb) return htmlWb;
    }

    if (lowerName.endsWith('.csv') || lowerName.endsWith('.tsv') || !trimmed.startsWith('<')) {
      const delimiter = detectCsvDelimiter(utf8Text);
      const csvWb = XLSX.read(utf8Text, {
        type: 'string',
        raw: true,
        FS: delimiter,
      });
      if (csvWb.SheetNames && csvWb.SheetNames.length > 0) {
        return csvWb;
      }
    }
  }

  try {
    const workbook = XLSX.read(buffer, {
      type: 'array',
      cellNF: true,
      cellText: true,
    });
    if (!workbook.SheetNames || workbook.SheetNames.length === 0) {
      throw new Error(`File "${file.name}" tidak memiliki lembar kerja (sheet).`);
    }
    return workbook;
  } catch (err) {
    const detail = err instanceof Error ? err.message : String(err);
    throw new Error(
      `Gagal mem-parsing file "${file.name}" (${detail}). Pastikan file berformat .xlsx, .xls, atau .csv UTF-8 yang tidak terenkripsi/rusak.`
    );
  }
}

/**
 * Mengambil nilai sel sebagai teks murni. Untuk sel bertipe angka dengan format custom nol di depan
 * (mis. 00123), nilai terformat (cell.w) tetap dipertahankan.
 */
function readCellAsText(cell: XLSX.CellObject | undefined): string {
  if (!cell) return '';

  if (cell.t === 's' || typeof cell.v === 'string') {
    return String(cell.v ?? '')
      .replace(/^'+/, '')
      .trim();
  }

  if (cell.t === 'n') {
    const formatted = typeof cell.w === 'string' ? cell.w.trim() : '';
    if (
      formatted &&
      !/[eE][+-]?\d+/.test(formatted) &&
      /^0\d+$/.test(formatted.replace(/[^0-9]/g, ''))
    ) {
      return formatted;
    }
    if (typeof cell.v === 'number' && Number.isFinite(cell.v)) {
      return Number.isInteger(cell.v)
        ? cell.v.toLocaleString('fullwide', { useGrouping: false })
        : String(cell.v);
    }
  }

  if (cell.t === 'b') {
    return cell.v ? 'TRUE' : 'FALSE';
  }

  if (typeof cell.w === 'string' && cell.w.trim() !== '') {
    return cell.w.replace(/^'+/, '').trim();
  }

  return String(cell.v ?? '')
    .replace(/^'+/, '')
    .trim();
}

interface NormalizedHeaderTokens {
  spaced: string;
  compact: string;
}

function normalizeHeaderTokens(raw: string): NormalizedHeaderTokens {
  const withoutParens = raw.trim().toLowerCase().replace(/\([^)]*\)/g, ' ');
  const spaced = withoutParens
    .replace(/[.:/\\_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const compact = raw
    .trim()
    .toLowerCase()
    .replace(/\([^)]*\)/g, '')
    .replace(/[^a-z0-9]/g, '');
  const fullCompact = raw
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
  return {
    spaced,
    compact: compact || fullCompact,
  };
}

