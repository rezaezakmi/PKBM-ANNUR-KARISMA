function normalizeRombelSpaces(raw: string): string {
  return String(raw || '').trim().replace(/\s+/g, ' ').toLowerCase();
}

function extractTrailingSectionNumber(raw: string): string {
  const clean = normalizeRombelSpaces(raw);
  // Tangkap angka rombel paralel di akhir (misal "kelas 10 cipanas 2" -> "2", "kelas 10 cipanas" -> "")
  const m = clean.match(/\bcipanas\s+(\d+)\s*$/i) || clean.match(/\b(?:kelas|kls)\s*\d+\s+[a-z]+\s+(\d+)\s*$/i);
  return m ? m[1] : '';
}

export function getPaketRank(paket?: string): number {
  if (paket === 'Paket A') return 1;
  if (paket === 'Paket B') return 2;
  if (paket === 'Paket C') return 3;
  return 9;
}

export function compareClassroomsByJenjang(a: Pick<Classroom, 'paket' | 'name' | 'gradeLevel'>, b: Pick<Classroom, 'paket' | 'name' | 'gradeLevel'>): number {
  const pDiff = getPaketRank(a.paket) - getPaketRank(b.paket);
  if (pDiff !== 0) return pDiff;
  const gA = Number(extractGradeHint(`${a.name} ${a.gradeLevel || ''}`) || 99);
  const gB = Number(extractGradeHint(`${b.name} ${b.gradeLevel || ''}`) || 99);
  if (gA !== gB) return gA - gB;
  const secA = Number(extractTrailingSectionNumber(a.name) || 1);
  const secB = Number(extractTrailingSectionNumber(b.name) || 1);
  if (secA !== secB) return secA - secB;
  return a.name.localeCompare(b.name, 'id');
}

