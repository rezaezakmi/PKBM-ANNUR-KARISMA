export function sortStudentsByJenjangAndName(students: Student[], classes: Classroom[] = []): Student[] {
  const clsMap = new Map(classes.map((c) => [c.id, c]));
  return [...students].sort((a, b) => {
    const clsA = clsMap.get(a.classId);
    const clsB = clsMap.get(b.classId);
    const cmp = compareClassroomsByJenjang(
      { paket: clsA?.paket || a.paket, name: clsA?.name || a.className, gradeLevel: clsA?.gradeLevel || '' },
      { paket: clsB?.paket || b.paket, name: clsB?.name || b.className, gradeLevel: clsB?.gradeLevel || '' }
    );
    if (cmp !== 0) return cmp;
    return a.fullName.localeCompare(b.fullName, 'id');
  });
}

function paketFromGradeNumber(grade: string | null): PaketType | undefined {
  if (!grade) return undefined;
  const num = Number(grade);
  if (num >= 1 && num <= 6) return 'Paket A';
  if (num >= 7 && num <= 9) return 'Paket B';
  if (num >= 10 && num <= 12) return 'Paket C';
  return undefined;
}

export function resolveStudentPlacement(
  student: Student,
  classes: Classroom[] = []
): {
  paket: PaketType;
  classId: string;
  className: string;
  fullClassLabel: string;
  shortClassLabel: string;
} {
  const clsById = student.classId ? classes.find((c) => c.id === student.classId) : undefined;
  const rawClassName = (student.className || '').trim();
  const classNamePaket = extractPaketFromText(rawClassName);
  const rawGradeHint = extractGradeHint(rawClassName);
  const gradePaket = paketFromGradeNumber(rawGradeHint);

  // Tentukan Paket sebenarnya tanpa tertipu sisa default "Paket A - Kelas 6A"
  let targetPaket: PaketType = student.paket || clsById?.paket || classNamePaket || gradePaket || 'Paket C';
  if (clsById && clsById.id !== 'cls_a6') {
    targetPaket = clsById.paket;
  } else if (targetPaket === 'Paket A') {
    if (classNamePaket && classNamePaket !== 'Paket A') {
      targetPaket = classNamePaket;
    } else if (gradePaket && gradePaket !== 'Paket A') {
      targetPaket = gradePaket;
    }
  }

  let resolvedClassId = clsById?.id || student.classId || '';
  let resolvedClassName = rawClassName;

  if (clsById && clsById.paket === targetPaket) {
    resolvedClassId = clsById.id;
    resolvedClassName = clsById.name;
  } else {
    const samePaketClasses = classes.filter((c) => c.paket === targetPaket);
    const cleanRawLower = normalizeRombelSpaces(rawClassName);
    const cleanRawShort = normalizeRombelSpaces(stripPaketPrefixFromClassName(rawClassName));
    const rawSectionNum = extractTrailingSectionNumber(rawClassName);

    // 1. Prioritaskan kecocokan persis (agar "10 CIPANAS 2" tidak pernah tertukar dengan "10 CIPANAS")
    const exactMatch = samePaketClasses.find((c) => {
      const cLower = normalizeRombelSpaces(c.name);
      const cShort = normalizeRombelSpaces(stripPaketPrefixFromClassName(c.name));
      return (
        (cleanRawLower && cLower === cleanRawLower) ||
        (cleanRawShort && cShort === cleanRawShort)
      );
    });

    // 2. Kecocokan parsial aman (wajib nomor paralel sama)
    const safePartial =
      !exactMatch && (cleanRawLower || cleanRawShort)
        ? samePaketClasses.find((c) => {
            if (extractTrailingSectionNumber(c.name) !== rawSectionNum) return false;
            const cLower = normalizeRombelSpaces(c.name);
            const cShort = normalizeRombelSpaces(stripPaketPrefixFromClassName(c.name));
            return (
              (cleanRawLower && cLower.includes(cleanRawLower)) ||
              (cleanRawShort && cShort.includes(cleanRawShort))
            );
          })
        : undefined;

    // 3. Fallback berdasarkan tingkat kelas & nomor paralel yang sama
    const matchingGrade =
      !exactMatch && !safePartial && rawGradeHint && samePaketClasses.length > 0
        ? samePaketClasses.find(
            (c) =>
              extractGradeHint(`${c.name} ${c.gradeLevel}`) === rawGradeHint &&
              extractTrailingSectionNumber(c.name) === rawSectionNum
          ) ||
          samePaketClasses.find(
            (c) => extractGradeHint(`${c.name} ${c.gradeLevel}`) === rawGradeHint
          )
        : undefined;

    if (exactMatch) {
      resolvedClassId = exactMatch.id;
      resolvedClassName = exactMatch.name;
    } else if (safePartial) {
      resolvedClassId = safePartial.id;
      resolvedClassName = safePartial.name;
    } else if (matchingGrade) {
      resolvedClassId = matchingGrade.id;
      resolvedClassName = matchingGrade.name;
    } else if (
      (!resolvedClassName || (classNamePaket && classNamePaket !== targetPaket)) &&
      samePaketClasses.length > 0
    ) {
      resolvedClassId = samePaketClasses[0].id;
      resolvedClassName = samePaketClasses[0].name;
    } else if (!resolvedClassName || (classNamePaket && classNamePaket !== targetPaket)) {
      resolvedClassName =
        targetPaket === 'Paket A'
          ? 'Paket A - Kelas 6 CIPANAS'
          : targetPaket === 'Paket B'
            ? 'Paket B - Kelas 7 CIPANAS'
            : 'Paket C - Kelas 10 CIPANAS';
    }
  }

  const fullClassLabel = formatStudentAccountClassLabel(targetPaket, resolvedClassName);
  const shortClassLabel = stripPaketPrefixFromClassName(fullClassLabel);

  return {
    paket: targetPaket,
    classId: resolvedClassId,
    className: resolvedClassName,
    fullClassLabel,
    shortClassLabel,
  };
}

export function getStudentsForClassroom(
  classroom: Classroom,
  students: Student[],
  allClasses: Classroom[] = []
): Student[] {
  const clsNameLower = normalizeRombelSpaces(classroom.name);
  const clsShortLower = normalizeRombelSpaces(stripPaketPrefixFromClassName(classroom.name));
  const clsGrade = extractGradeHint(`${classroom.name} ${classroom.gradeLevel}`);
  const clsSectionNum = extractTrailingSectionNumber(classroom.name);
  const samePaketClassCount = allClasses.filter((c) => c.paket === classroom.paket).length;

  return students.filter((stu) => {
    const placed = resolveStudentPlacement(stu, allClasses);
    if (placed.classId && placed.classId === classroom.id) return true;
    if (placed.paket !== classroom.paket) return false;
    const stuNameLower = normalizeRombelSpaces(placed.className);
    const stuShortLower = normalizeRombelSpaces(placed.shortClassLabel);
    if (stuNameLower === clsNameLower || stuShortLower === clsShortLower) return true;
    // Jika classId murid tidak ada lagi di daftar kelas, cocokkan berdasarkan tingkat & nomor paralel yang sama
    const hasValidExistingClass = allClasses.some((c) => c.id === placed.classId);
    if (!hasValidExistingClass) {
      const stuGrade = extractGradeHint(placed.className);
      const stuSectionNum = extractTrailingSectionNumber(placed.className);
      if (clsGrade && stuGrade && clsGrade === stuGrade && clsSectionNum === stuSectionNum) return true;
      if (samePaketClassCount === 1) return true;
    }
    return false;
  });
}

function inferPaketStrict(
  paketRaw: string,
  classRaw: string,
  gradeRaw = ''
): { paket: PaketType; invalidReason?: string } {
  const cleanP = cleanOptionalText(paketRaw).toUpperCase();
  if (cleanP) {
    if (cleanP.includes('PAKET A') || cleanP === 'A' || cleanP.includes('SD') || cleanP.includes('ULA')) {
      return { paket: 'Paket A' };
    }
    if (cleanP.includes('PAKET B') || cleanP === 'B' || cleanP.includes('SMP') || cleanP.includes('WUSTHA')) {
      return { paket: 'Paket B' };
    }
    if (cleanP.includes('PAKET C') || cleanP === 'C' || cleanP.includes('SMA') || cleanP.includes('SMK') || cleanP.includes('ULYA')) {
      return { paket: 'Paket C' };
    }
    return {
      paket: 'Paket C',
      invalidReason: `Nilai kolom Paket "${paketRaw}" tidak dikenali (gunakan Paket A, Paket B, atau Paket C).`,
    };
  }

  const combinedUpper = `${cleanOptionalText(classRaw)} ${cleanOptionalText(gradeRaw)}`.toUpperCase();
  if (combinedUpper.includes('PAKET A') || /\bSD\b/.test(combinedUpper)) {
    return { paket: 'Paket A' };
  }
  if (combinedUpper.includes('PAKET B') || /\bSMP\b/.test(combinedUpper)) {
    return { paket: 'Paket B' };
  }
  if (combinedUpper.includes('PAKET C') || /\bSMA\b|\bSMK\b/.test(combinedUpper)) {
    return { paket: 'Paket C' };
  }

  const gradeHint = extractGradeHint(classRaw) || extractGradeHint(gradeRaw);
  if (gradeHint) {
    const num = Number(gradeHint);
    if (num >= 1 && num <= 6) return { paket: 'Paket A' };
    if (num >= 7 && num <= 9) return { paket: 'Paket B' };
    if (num >= 10 && num <= 12) return { paket: 'Paket C' };
  }

  return { paket: 'Paket C' };
}

function parseGenderStrict(raw: string): { gender: 'L' | 'P'; invalidReason?: string } {
  const clean = cleanOptionalText(raw).toUpperCase();
  if (!clean) return { gender: 'L' };
  if (clean === 'L' || clean === 'LAKI-LAKI' || clean === 'LAKI LAKI' || clean === 'LK' || clean === 'PRIA' || clean === 'MALE' || clean === 'M') {
    return { gender: 'L' };
  }
  if (clean === 'P' || clean.startsWith('PEREMPUAN') || clean === 'PR' || clean.startsWith('WANITA') || clean === 'FEMALE' || clean === 'F') {
    return { gender: 'P' };
  }
  return {
    gender: 'L',
    invalidReason: `Jenis Kelamin "${raw}" tidak valid (gunakan L atau P).`,
  };
}

function parseStatusStrict(raw: string): { status: Student['status']; invalidReason?: string } {
  const clean = cleanOptionalText(raw);
  if (!clean) return { status: 'Aktif' };
  const lower = clean.toLowerCase();
  if (lower === 'aktif' || lower === 'terdaftar') return { status: 'Aktif' };
  if (lower === 'cuti') return { status: 'Cuti' };
  if (lower === 'lulus' || lower === 'tamat') return { status: 'Lulus' };
  if (lower === 'nonaktif' || lower === 'non aktif' || lower === 'non-aktif' || lower === 'keluar' || lower === 'mutasi') {
    return { status: 'Nonaktif' };
  }
  return {
    status: 'Aktif',
    invalidReason: `Status "${raw}" tidak valid (gunakan Aktif, Cuti, Lulus, atau Nonaktif).`,
  };
}

function resolveTargetClassName(
  rowClassName: string,
  rowGradeRaw: string,
  rowPaket: PaketType,
  classes: Classroom[]
): string {
  const cleanClass = normalizeRombelSpaces(rowClassName);
  const cleanClassShort = normalizeRombelSpaces(stripPaketPrefixFromClassName(rowClassName));
  const cleanGrade = normalizeRombelSpaces(rowGradeRaw);
  const gradeHint = extractGradeHint(rowClassName) || extractGradeHint(rowGradeRaw);
  const formattedExplicit = rowClassName.trim()
    ? formatStudentAccountClassLabel(rowPaket, rowClassName)
    : '';

  if (classes.length > 0) {
    const samePaketClasses = classes.filter((c) => c.paket === rowPaket);

    // 1. Kecocokan persis nama lengkap / nama pendek di dalam paket yang sama atau semua kelas
    if (cleanClass) {
      const exactSamePaket = samePaketClasses.find((c) => {
        const cLower = normalizeRombelSpaces(c.name);
        const cShort = normalizeRombelSpaces(stripPaketPrefixFromClassName(c.name));
        return cLower === cleanClass || cShort === cleanClassShort;
      });
      if (exactSamePaket) return exactSamePaket.name;

      const exactAny = classes.find((c) => normalizeRombelSpaces(c.name) === cleanClass);
      if (exactAny) return exactAny.name;

      // Jika spreadsheet menyebut nama rombel spesifik (misal "Paket C - Kelas 10 CIPANAS 2"),
      // pertahankan nama rombel aslinya agar rombel dibuat otomatis persis sesuai spreadsheet!
      if (formattedExplicit) {
        return formattedExplicit;
      }
    }

    const pool = samePaketClasses.length > 0 ? samePaketClasses : classes;

    if (gradeHint) {
      const gradeMatch = pool.find((c) => {
        if (samePaketClasses.length > 0 && c.paket !== rowPaket) return false;
        const cHint = extractGradeHint(`${c.name} ${c.gradeLevel}`);
        return cHint === gradeHint;
      });
      if (gradeMatch) return gradeMatch.name;
    }

    if (cleanGrade) {
      const gradePartial = samePaketClasses.find(
        (c) =>
          normalizeRombelSpaces(c.name).includes(cleanGrade) ||
          normalizeRombelSpaces(c.gradeLevel).includes(cleanGrade)
      );
      if (gradePartial) return gradePartial.name;
    }

    if (samePaketClasses.length > 0) {
      return samePaketClasses[0].name;
    }
  }

  if (formattedExplicit) {
    return formattedExplicit;
  }

  if (gradeHint && DEFAULT_STANDARD_CLASS_BY_GRADE[gradeHint]) {
    const std = DEFAULT_STANDARD_CLASS_BY_GRADE[gradeHint];
    if (std.paket === rowPaket) return std.name;
  }

  if (gradeHint) {
    return `${rowPaket} - Kelas ${gradeHint}`;
  }
  if (rowPaket === 'Paket A') return 'Paket A - Kelas 6 CIPANAS';
  if (rowPaket === 'Paket B') return 'Paket B - Kelas 7 CIPANAS';
  return 'Paket C - Kelas 10 CIPANAS';
}

const FOOTER_NOISE_PATTERNS = [
  /^jumlah$/i,
  /^total$/i,
  /^mengetahui/i,
  /^kepala\s+(pkbm|sekolah)/i,
  /^dicetak/i,
  /^sumber\s*:/i,
];

export async function parseStudentsExcelWithPreview(
  file: File,
  existingStudents: Student[] = [],
  classes: Classroom[] = []
): Promise<StudentImportParseResult> {
  const workbook = await readSpreadsheetWorkbook(file);

  let bestExtracted: ExtractedSheetMatrix | null = null;
  for (const sheetName of workbook.SheetNames) {
    const sheet = workbook.Sheets[sheetName];
    if (!sheet) continue;
    const extracted = extractSheetWithExactRows(sheet, sheetName);
    if (!extracted) continue;
    if (!bestExtracted || extracted.score > bestExtracted.score) {
      bestExtracted = extracted;
    }
  }

  if (!bestExtracted) {
    return {
      fileName: file.name,
      sheetName: workbook.SheetNames[0] || '-',
      totalRowsScanned: 0,
      detectedHeaders: [],
      missingRequiredColumns: ['Nama Lengkap'],
      missingOptionalColumns: [],
      fatalError: `Sheet "${workbook.SheetNames[0] || '-'}" pada file "${file.name}" kosong atau tidak berisi tabel data.`,
      rows: [],
    };
  }

  const missingRequiredColumns: string[] = [];
  const missingOptionalColumns: string[] = [];

  for (const colDef of EXPECTED_TEMPLATE_COLUMNS) {
    if (bestExtracted.colMap[colDef.field] === undefined) {
      if (colDef.required) missingRequiredColumns.push(colDef.label);
      else missingOptionalColumns.push(colDef.label);
    }
  }

  if (missingRequiredColumns.length > 0) {
    const detectedDesc =
      bestExtracted.rawHeaders.length > 0
        ? bestExtracted.rawHeaders.join(', ')
        : '(tidak ada header teks terdeteksi)';
    return {
      fileName: file.name,
      sheetName: bestExtracted.sheetName,
      totalRowsScanned: bestExtracted.dataRows.length,
      detectedHeaders: bestExtracted.rawHeaders,
      missingRequiredColumns,
      missingOptionalColumns,
      fatalError: `Kolom wajib tidak ditemukan: ${missingRequiredColumns.join(', ')}. Kolom yang terdeteksi di baris header (${bestExtracted.headerRowIndex + 1}): [${detectedDesc}].`,
      rows: [],
    };
  }

  if (bestExtracted.dataRows.length === 0) {
    return {
      fileName: file.name,
      sheetName: bestExtracted.sheetName,
      totalRowsScanned: 0,
      detectedHeaders: bestExtracted.rawHeaders,
      missingRequiredColumns: [],
      missingOptionalColumns,
      fatalError: `Header kolom berhasil ditemukan di sheet "${bestExtracted.sheetName}", tetapi tidak ada baris data murid yang terisi (semua baris di bawah header kosong).`,
      rows: [],
    };
  }

  const existingNisSet = new Set(existingStudents.map((s) => s.nis.trim().toLowerCase()).filter(Boolean));
  const usedNisInFile = new Set<string>();
  let autoSeq = 1;

  const nextAutoNis = (): string => {
    while (true) {
      const candidate = `2026${String(autoSeq++).padStart(4, '0')}`;
      if (!existingNisSet.has(candidate.toLowerCase()) && !usedNisInFile.has(candidate.toLowerCase())) {
        return candidate;
      }
    }
  };

  const getField = (cells: string[], field: StudentColumnField): string => {
    const colIdx = bestExtracted!.colMap[field];
    if (colIdx === undefined) return '';
    return cells[colIdx] ?? '';
  };

  const previewRows: StudentImportPreviewRow[] = [];

  for (const { excelRowNumber, cells } of bestExtracted.dataRows) {
    // Pastikan sekali lagi baris bukan semua berisi '-' atau spasi kosong
    const meaningfulValues = Object.values(bestExtracted.colMap).map((idx) =>
      idx !== undefined ? cleanOptionalText(cells[idx] ?? '') : ''
    );
    if (meaningfulValues.every((v) => v === '')) continue;

    const rawNisRaw = getField(cells, 'nis');
    const rawNisnRaw = getField(cells, 'nisn');
    const rawNameRaw = getField(cells, 'fullName');
    const rawGenderRaw = getField(cells, 'gender');
    const rawPaketRaw = getField(cells, 'paket');
    const rawClassRaw = getField(cells, 'className');
    const rawGradeRaw = getField(cells, 'gradeRaw');
    const rawEmailRaw = getField(cells, 'email');
    const rawPhoneRaw = getField(cells, 'phone');
    const rawAddressRaw = getField(cells, 'address');
    const rawGuardianRaw = getField(cells, 'guardianName');
    const rawStatusRaw = getField(cells, 'status');

    const fullName = cleanOptionalText(rawNameRaw);
    if (FOOTER_NOISE_PATTERNS.some((re) => re.test(fullName))) continue;
    if (resolveHeaderField(fullName) === 'fullName') continue;

    // NIS & NISN dipertahankan sebagai teks agar angka 0 di depan tidak hilang
    const rawNis = rawNisRaw.trim().replace(/^'+/, '');
    const cleanNis = rawNis === '-' ? '' : rawNis.replace(/\s+/g, '');
    const rawNisn = rawNisnRaw.trim().replace(/^'+/, '');
    const nisn = rawNisn === '-' ? '' : rawNisn.replace(/\s+/g, '');

    const errors: string[] = [];
    const warnings: string[] = [];

    // Validasi Nama Lengkap
    if (!fullName) {
      errors.push(`Kolom "Nama Lengkap" kosong.`);
    } else if (fullName.length < 2) {
      errors.push(`"Nama Lengkap" ("${fullName}") minimal 2 karakter.`);
    } else if (fullName.length > 120) {
      errors.push(`"Nama Lengkap" melebihi 120 karakter (${fullName.length} karakter).`);
    }

    // Validasi NIS (NIS boleh kosong -> dibuat otomatis agar valid untuk database)
    let resolvedNis = cleanNis;
    let nisAutoGenerated = false;
    if (!cleanNis) {
      nisAutoGenerated = true;
      resolvedNis = nextAutoNis();
      warnings.push(`NIS kosong — akan dibuat otomatis sebagai "${resolvedNis}".`);
    } else {
      if (cleanNis.length < 3) {
        errors.push(`NIS "${cleanNis}" kurang dari 3 karakter (minimal 3 karakter, atau kosongkan).`);
      } else if (cleanNis.length > 32) {
        errors.push(`NIS "${cleanNis}" melebihi 32 karakter.`);
      }
      if (usedNisInFile.has(cleanNis.toLowerCase())) {
        warnings.push(`NIS "${cleanNis}" duplikat di dalam file ini (baris berikutnya akan menimpa).`);
      }
    }
    usedNisInFile.add(resolvedNis.toLowerCase());

    // Validasi NISN
    if (nisn.length > 32) {
      errors.push(`NISN "${nisn}" melebihi 32 karakter.`);
    }

    // Validasi Jenis Kelamin
    const genderParsed = parseGenderStrict(rawGenderRaw);
    if (genderParsed.invalidReason) {
      errors.push(genderParsed.invalidReason);
    }

    // Validasi Paket (gabungkan kolom Paket, Kelas/Rombel, dan Tingkat)
    const paketParsed = inferPaketStrict(rawPaketRaw, rawClassRaw, rawGradeRaw);
    if (paketParsed.invalidReason) {
      errors.push(paketParsed.invalidReason);
    }

    const cleanClassText = cleanOptionalText(rawClassRaw);
    const cleanGradeText = cleanOptionalText(rawGradeRaw);
    const className = (cleanClassText || cleanGradeText).slice(0, 80);
    const resolvedClassName = resolveTargetClassName(
      cleanClassText,
      cleanGradeText,
      paketParsed.paket,
      classes
    );

    // Validasi Email
    const email = cleanOptionalText(rawEmailRaw);
    if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      errors.push(`Format Email "${email}" tidak valid.`);
    } else if (email.length > 160) {
      errors.push(`Email melebihi 160 karakter.`);
    }

    // Validasi Telepon, Alamat, Nama Wali
    const phone = cleanOptionalText(rawPhoneRaw);
    if (phone.length > 32) {
      errors.push(`Telepon melebihi 32 karakter.`);
    }

    const address = cleanOptionalText(rawAddressRaw);
    if (address.length > 250) {
      errors.push(`Alamat melebihi 250 karakter.`);
    }

    const guardianName = cleanOptionalText(rawGuardianRaw);
    if (guardianName.length > 120) {
      errors.push(`Nama Wali melebihi 120 karakter.`);
    }

    // Validasi Status
    const statusParsed = parseStatusStrict(rawStatusRaw);
    if (statusParsed.invalidReason) {
      errors.push(statusParsed.invalidReason);
    }

    const isUpdate = !nisAutoGenerated && existingNisSet.has(resolvedNis.toLowerCase());
    if (isUpdate) {
      warnings.push(`NIS "${resolvedNis}" sudah ada — data murid lama akan diperbarui.`);
    }

    previewRows.push({
      rowNumber: excelRowNumber,
      rawNis: cleanNis,
      resolvedNis,
      nisAutoGenerated,
      nisn,
      fullName,
      gender: genderParsed.gender,
      paket: paketParsed.paket,
      className,
      resolvedClassName,
      email,
      phone,
      address,
      guardianName,
      status: statusParsed.status,
      valid: errors.length === 0,
      errors,
      warnings,
      isUpdate,
    });
  }

  if (previewRows.length === 0) {
    return {
      fileName: file.name,
      sheetName: bestExtracted.sheetName,
      totalRowsScanned: bestExtracted.dataRows.length,
      detectedHeaders: bestExtracted.rawHeaders,
      missingRequiredColumns,
      missingOptionalColumns,
      fatalError: `Tidak ditemukan baris data murid yang valid di sheet "${bestExtracted.sheetName}". Semua baris terdeteksi kosong.`,
      rows: [],
    };
  }

  return {
    fileName: file.name,
    sheetName: bestExtracted.sheetName,
    totalRowsScanned: previewRows.length,
    detectedHeaders: bestExtracted.rawHeaders,
    missingRequiredColumns,
    missingOptionalColumns,
    rows: previewRows,
  };
}

export async function parseStudentsExcelFile(file: File): Promise<Array<Partial<Student>>> {
  const result = await parseStudentsExcelWithPreview(file);
  if (result.fatalError) {
    throw new Error(result.fatalError);
  }
  return result.rows
    .filter((r) => r.valid)
    .map((r) => ({
      nis: r.resolvedNis,
      nisn: r.nisn,
      fullName: r.fullName,
      gender: r.gender,
      paket: r.paket,
      className: r.className || r.resolvedClassName,
      email: r.email,
      phone: r.phone,
      address: r.address,
      guardianName: r.guardianName,
      status: r.status,
    }));
}
