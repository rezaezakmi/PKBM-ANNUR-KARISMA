function resolveHeaderField(rawHeader: string): StudentColumnField | null {
  const { compact } = normalizeHeaderTokens(rawHeader);
  if (!compact) return null;
  if (HEADER_ALIAS_TO_FIELD[compact]) return HEADER_ALIAS_TO_FIELD[compact];
  const fullCompact = rawHeader.trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  if (HEADER_ALIAS_TO_FIELD[fullCompact]) return HEADER_ALIAS_TO_FIELD[fullCompact];
  return null;
}

interface ExtractedSheetMatrix {
  sheetName: string;
  headerRowIndex: number;
  rawHeaders: string[];
  colMap: Partial<Record<StudentColumnField, number>>;
  dataRows: Array<{
    excelRowNumber: number;
    cells: string[];
  }>;
  score: number;
}

function isNumberingSubRow(cells: string[]): boolean {
  const nonEmpty = cells.map((c) => c.trim()).filter(Boolean);
  if (nonEmpty.length < 2) return false;
  return nonEmpty.every((c) => /^\(?\d{1,2}\)?$/.test(c));
}

function extractSheetWithExactRows(sheet: XLSX.WorkSheet, sheetName: string): ExtractedSheetMatrix | null {
  const ref = sheet['!ref'];
  if (!ref) return null;

  const range = XLSX.utils.decode_range(ref);
  const totalRows = range.e.r - range.s.r + 1;
  const totalCols = Math.min(range.e.c - range.s.c + 1, 60);
  if (totalRows < 1 || totalCols < 1) return null;

  const getRowCells = (r: number): string[] => {
    const row: string[] = [];
    for (let c = range.s.c; c <= range.s.c + totalCols - 1; c++) {
      const addr = XLSX.utils.encode_cell({ r, c });
      row.push(readCellAsText(sheet[addr]));
    }
    return row;
  };

  // Cari baris header terbaik dalam 30 baris pertama
  let bestHeaderRow = range.s.r;
  let bestScore = -1;
  let bestColMap: Partial<Record<StudentColumnField, number>> = {};
  let bestHeaders: string[] = [];

  const scanLimit = Math.min(range.e.r, range.s.r + 30);
  for (let r = range.s.r; r <= scanLimit; r++) {
    const cells = getRowCells(r);
    const colMap: Partial<Record<StudentColumnField, number>> = {};
    let score = 0;

    cells.forEach((cellVal, idx) => {
      const field = resolveHeaderField(cellVal);
      if (field && colMap[field] === undefined) {
        colMap[field] = idx;
        if (field === 'fullName') score += 5;
        else if (field === 'nis' || field === 'nisn') score += 4;
        else score += 2;
      }
    });

    if (score > bestScore) {
      bestScore = score;
      bestHeaderRow = r;
      bestColMap = colMap;
      bestHeaders = cells;
    }
  }

  let startDataRow = bestHeaderRow + 1;
  if (startDataRow <= range.e.r) {
    const nextRowCells = getRowCells(startDataRow);
    if (isNumberingSubRow(nextRowCells)) {
      startDataRow++;
    }
  }

  const dataRows: Array<{ excelRowNumber: number; cells: string[] }> = [];
  for (let r = startDataRow; r <= range.e.r; r++) {
    const cells = getRowCells(r);
    // Abaikan baris yang kosong (semua kolom kosong)
    const hasNonEmpty = cells.some((val) => val.trim() !== '');
    if (!hasNonEmpty) continue;
    dataRows.push({
      excelRowNumber: r + 1,
      cells,
    });
  }

  return {
    sheetName,
    headerRowIndex: bestHeaderRow,
    rawHeaders: bestHeaders.map((h) => h.trim()).filter(Boolean),
    colMap: bestColMap,
    dataRows,
    score: bestScore,
  };
}

function cleanOptionalText(val: string): string {
  const trimmed = val.trim();
  if (!trimmed || trimmed === '-' || trimmed.toLowerCase() === 'null' || trimmed.toLowerCase() === 'undefined') {
    return '';
  }
  return trimmed;
}

export function extractGradeHint(raw: string): string | null {
  const upper = raw.toUpperCase();
  if (!upper.trim()) return null;
  // Cek angka tingkat paling tinggi terlebih dahulu (12, 11, 10) termasuk diikuti huruf rombel seperti "12A", "10IPS"
  if (/(?:^|[^0-9])12(?:[^0-9]|$)/.test(upper) || /\bXII[A-Z0-9-]*\b/.test(upper)) return '12';
  if (/(?:^|[^0-9])11(?:[^0-9]|$)/.test(upper) || /\bXI[A-Z0-9-]*\b/.test(upper)) return '11';
  if (/(?:^|[^0-9])10(?:[^0-9]|$)/.test(upper) || /\bX[A-Z0-9-]*\b/.test(upper)) return '10';
  if (/(?:^|[^0-9])9(?:[^0-9]|$)/.test(upper) || /\bIX[A-Z0-9-]*\b/.test(upper)) return '9';
  if (/(?:^|[^0-9])8(?:[^0-9]|$)/.test(upper) || /\bVIII[A-Z0-9-]*\b/.test(upper)) return '8';
  if (/(?:^|[^0-9])7(?:[^0-9]|$)/.test(upper) || /\bVII[A-Z0-9-]*\b/.test(upper)) return '7';
  if (/(?:^|[^0-9])6(?:[^0-9]|$)/.test(upper) || /\bVI[A-Z0-9-]*\b/.test(upper)) return '6';
  if (/(?:^|[^0-9])5(?:[^0-9]|$)/.test(upper) || /\bV[A-Z0-9-]*\b/.test(upper)) return '5';
  if (/(?:^|[^0-9])4(?:[^0-9]|$)/.test(upper) || /\bIV[A-Z0-9-]*\b/.test(upper)) return '4';
  if (/(?:^|[^0-9])3(?:[^0-9]|$)/.test(upper) || /\bIII[A-Z0-9-]*\b/.test(upper)) return '3';
  if (/(?:^|[^0-9])2(?:[^0-9]|$)/.test(upper) || /\bII[A-Z0-9-]*\b/.test(upper)) return '2';
  if (/(?:^|[^0-9])1(?:[^0-9]|$)/.test(upper) || /\bI[A-Z0-9-]*\b/.test(upper)) return '1';
  return null;
}

export function extractPaketFromText(raw: string): PaketType | undefined {
  const upper = (raw || '').toUpperCase();
  if (!upper.trim()) return undefined;
  if (/\bPAKET\s*A\b/.test(upper)) return 'Paket A';
  if (/\bPAKET\s*B\b/.test(upper)) return 'Paket B';
  if (/\bPAKET\s*C\b/.test(upper)) return 'Paket C';
  return undefined;
}

export function stripPaketPrefixFromClassName(className: string): string {
  const cleaned = (className || '')
    .trim()
    .replace(/^paket\s+[abc]\s*[-–—:/|]\s*/i, '')
    .replace(/^paket\s+[abc]\s+/i, '')
    .trim();
  return cleaned || (className || '').trim();
}

export function formatStudentAccountClassLabel(paket: PaketType, className: string): string {
  const cleanClass = className.trim();
  if (!cleanClass) return paket;
  const embeddedPaket = extractPaketFromText(cleanClass);
  if (embeddedPaket && embeddedPaket !== paket) {
    const stripped = stripPaketPrefixFromClassName(cleanClass);
    return `${paket} - ${stripped}`.slice(0, 120);
  }
  if (cleanClass.toLowerCase().includes(paket.toLowerCase())) {
    return cleanClass.slice(0, 120);
  }
  return `${paket} - ${cleanClass}`.slice(0, 120);
}

